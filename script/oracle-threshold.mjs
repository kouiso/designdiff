/**
 * 合否を分ける残差のしきい値。
 *
 * 2箇所に書くと、収束の判定とCIの検査が黙って別々の「正解」を持つ。
 * 動かすときは必ずここだけを動かす。
 */

/**
 * 合成した検体に対するしきい値。
 *
 * 一致する検体の残差は 0、一致しない検体は 2.0% 以上で、間が大きく空いている。
 * 0.5% はその空白の中に置いた値で、どちらへも寄っていない。
 */
export const RESIDUAL_FAIL_THRESHOLD = 0.005;

/**
 * 実際に撮った画面に対するしきい値。
 *
 * 実画面には文字のふちのぼかしと書き出し時の丸めが乗るので、合成した検体で
 * 決めた値がそのまま使えるとは限らない。校正の実測が済むまでは同じ値を置き、
 * 動かすときは測った数字と証拠を添えて、別のコミットで動かす。
 */
export const LIVE_RESIDUAL_FAIL_THRESHOLD = 0.005;
